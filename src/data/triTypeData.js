/**
 * Look up a tri-type by the three center winners.
 * The CSV keys are the three numbers sorted numerically ascending (e.g. 3,5,8 → "358"),
 * NOT in head-heart-gut center order. Sort before lookup.
 */
export function getTriType(head, heart, gut) {
  const code = [head, heart, gut].sort((a, b) => a - b).join('');
  return TRITYPES[code] || null;
}

/**
 * Get the active tri-type data for a user, accounting for counter-phobic type 6.
 * If the user's head type is 6 and isCounterphobic is true, merges cpData fields
 * over the standard fields so the caller always gets the right mission/description.
 */
export function getActiveTriTypeData(tritype, isCounterphobic = false) {
  if (!tritype) return null;
  const data = TRITYPES[tritype];
  if (!data) return null;
  if (isCounterphobic && data.cpData) {
    return { ...data, ...data.cpData };
  }
  return data;
}

/**
 * Extract just the English name from a sephira string like "חכמה (Chochmah)".
 */
export function sephiraEnglish(str) {
  const match = str.match(/\(([^)]+)\)/);
  if (!match) return str;
  return match[1].replace(/, phobic|, cp/g, '').trim();
}
